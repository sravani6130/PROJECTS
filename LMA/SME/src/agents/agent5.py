class Slide(BaseModel):
    heading: str = Field(..., description="Title of the slide")
    points: List[str] = Field(
        ..., 
        description="Bullet points for the slide (max 4)"
    )

class Agent5Output(BaseModel):
    name: str = Field(..., description="Title of the presentation")
    slides: List[Slide] = Field(..., description="List of slides")
    
def sanitize_filename(name: str) -> str:
    """
    Convert a presentation title into a clean filename:
    lowercase, underscores instead of spaces, alphanumeric only.
    """
    name = name.strip().lower()
    name = re.sub(r"\s+", "_", name)          # replace spaces with _
    name = re.sub(r"[^a-z0-9_]", "", name)    # remove invalid chars
    return name + ".pptx"


def create_ppt_from_slidedeck(slidedeck: Agent5Output, output_dir: str = "./") -> str:
    prs = Presentation()
    
    TITLE_LAYOUT = 0  # title slide layout
    slide = prs.slides.add_slide(prs.slide_layouts[TITLE_LAYOUT])
    title = slide.shapes.title
    subtitle = slide.placeholders[1]

    title.text = slidedeck.name
    title.text_frame.paragraphs[0].font.size = Pt(44)
    title.text_frame.paragraphs[0].font.bold = True

    subtitle.text = "Generated by SME System"
    subtitle.text_frame.paragraphs[0].font.size = Pt(24)

    # -----------------------------------------------------
    # Create CONTENT SLIDES
    # -----------------------------------------------------
    CONTENT_LAYOUT = 1  # title + content layout

    for slide_obj in slidedeck.slides:
        slide = prs.slides.add_slide(prs.slide_layouts[CONTENT_LAYOUT])

        # Heading
        heading_shape = slide.shapes.title
        heading_shape.text = slide_obj.heading
        heading_shape.text_frame.paragraphs[0].font.size = Pt(36)
        heading_shape.text_frame.paragraphs[0].font.bold = True

        # Bullets
        body_shape = slide.shapes.placeholders[1]
        text_frame = body_shape.text_frame
        text_frame.clear()
        text_frame.word_wrap = True

        for point in slide_obj.points:
            p = text_frame.add_paragraph()
            p.text = point
            p.level = 0
            p.font.size = Pt(24)

    filename = sanitize_filename(slidedeck.name)
    output_path = f"{output_dir.rstrip('/')}/{filename}"

    prs.save(output_path)
    return output_path

